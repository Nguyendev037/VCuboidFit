// Read-only browser acceptance for H04; invoke with node e2e/u4u5-browser.mjs.
import { chromium } from "playwright";
import assert from "node:assert/strict";
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
const evidence=path.resolve("../../../planning/12_2026-10-14_demo-ui-thursday/evidence/U4U5");
const origin=process.env.UI_ORIGIN || "http://127.0.0.1:3014";
const browser=await chromium.launch();
const context=await browser.newContext({viewport:{width:1440,height:900},permissions:["clipboard-read","clipboard-write"]});
const page=await context.newPage();
const errors=[];page.on("pageerror",error=>errors.push(error.message));
const measured={};
try {
 await mkdir(evidence,{recursive:true});
 await page.goto(`${origin}/?present=1`);
 await page.waitForFunction(()=>document.documentElement.dataset.present==="1");
 measured.presentation=await page.evaluate(()=>({font:getComputedStyle(document.documentElement).fontSize,stored:localStorage.getItem("vcf.present")}));
 assert.deepEqual(measured.presentation,{font:"18px",stored:"1"});
 const bench=await (await page.request.get(`${origin}/demo/bench_pitch.json`)).json();
 const metrics=await page.locator("table tbody tr").allTextContents();
 for(const [index,id] of ["M0","M1","M2","M3"].entries()){
  const m=bench.methods[id]; if(m?.status==="ok") for(const number of [m.iy,m.ci_lo,m.ci_hi]) assert(metrics[index].includes(number.toFixed(3)));
 }
 measured.metricsMatch=true;
 await page.getByRole("link",{name:"Vào dashboard",exact:true}).click();
 await page.locator("[data-advanced-params]").waitFor({state:"attached"});
 assert.equal(await page.locator("[data-advanced-params]").isVisible(),false);
 measured.persistedNavigation=true;
 await page.goto(`${origin}/dashboard?present=0`);
 await page.waitForFunction(()=>document.documentElement.dataset.present==="0");
 assert.equal(await page.locator("[data-advanced-params]").isVisible(),true);
 measured.explicitExit=true;
 // A genuine 503 envelope is replayed to test recovery without stopping other workers.
 const recovery=async route=>route.fulfill({status:503,contentType:"application/json",body:JSON.stringify({error:{code:"worker_down",message:"Worker offline probe"}})});
 await page.route("**/api/jobs",recovery);
 await page.goto(`${origin}/dashboard`);
 await page.getByText("Worker chưa chạy",{exact:true}).waitFor();
 await page.getByRole("button",{name:"Sao chép lệnh",exact:true}).click();
 measured.clipboard=await page.evaluate(()=>navigator.clipboard.readText());
 assert(measured.clipboard.includes('WORKSPACE="model/workspace"'));
 assert(measured.clipboard.includes("uvicorn"));
 await page.getByRole("button",{name:"Thử lại",exact:true}).first().click();
 await page.unroute("**/api/jobs",recovery);
 const framesResponse=await page.request.get(`${origin}/api/jobs/m2_mini/selections/6987e5e71164/frames?budget=0.05&page=1&pageSize=200`);
 assert.equal(framesResponse.status(),200);
 const frames=(await framesResponse.json()).items;
 assert.equal(frames.length,21);measured.batch=frames.length;
 const frameUrl=token=>`${origin}/frame/${token}?jobId=m2_mini&sel=6987e5e71164&budget=0.05`;
 await page.goto(`${origin}/review/m2_mini?sel=6987e5e71164&budget=0.05`);
 const exportFailure=async route=>route.fulfill({status:502,contentType:"application/json",body:JSON.stringify({error:{code:"export_probe",message:"Export unavailable"}})});
 await page.route("**/export-images.zip?**",exportFailure);
 await page.getByRole("button",{name:"Xuất ảnh hiếm (ZIP)",exact:true}).click();
 await page.getByText(/Xuất ZIP lỗi: 502/).waitFor();
 await page.getByRole("button",{name:"Tải lại",exact:true}).click();
 await page.getByText(/Xuất ZIP lỗi: 502/).waitFor();
 measured.exportRetry=true;
 await page.unroute("**/export-images.zip?**",exportFailure);
 await page.goto(frameUrl(frames[0].sampleToken));
 await page.getByRole("button",{name:"Frame kế tiếp",exact:true}).waitFor();
 assert(await page.getByLabel("Chú giải box").isVisible());
 await page.getByRole("button",{name:"Đặt lại góc nhìn (R)",exact:true}).click();
 await page.keyboard.press("ArrowRight");
 await page.waitForURL(`**/frame/${frames[1].sampleToken}?**`);
 await page.getByRole("button",{name:"Frame trước",exact:true}).waitFor();
 await page.keyboard.press("ArrowLeft");
 await page.waitForURL(`**/frame/${frames[0].sampleToken}?**`);
 measured.arrowsAndReset=true;
 await page.goto(`${origin}/frame/absent?jobId=absent&sel=absent`);
 await page.getByText("Không tìm thấy job/selection/frame",{exact:true}).waitFor();
 assert(await page.getByRole("link",{name:"Về dashboard",exact:true}).isVisible());
 measured.notFound=true;
 const empty=async route=>route.fulfill({status:200,contentType:"application/json",body:JSON.stringify({items:[],total:0,budgetB:0})});
 await page.route("**/api/jobs/m2_mini/selections/6987e5e71164/frames?**",empty);
 await page.goto(frameUrl(frames[0].sampleToken));
 await page.getByText("Lô này chưa có frame. Chọn lô khác để xem.",{exact:true}).waitFor();
 measured.emptyBatch=true;
 await page.unroute("**/api/jobs/m2_mini/selections/6987e5e71164/frames?**",empty);
 const missing=async route=>route.fulfill({status:404,body:"missing"});
 await page.route("**/api/media/**/images/**",missing);
 await page.goto(frameUrl(frames[0].sampleToken));
 await page.getByText(/^Thiếu ảnh:/).first().waitFor();
 assert(await page.getByLabel("Chú giải box").isVisible());
 measured.missingMedia=true;
 await page.unroute("**/api/media/**/images/**",missing);
 await page.route("**/api/media/**/lidar/**",missing);
 await page.goto(frameUrl(frames[0].sampleToken));
 await page.getByText("Thử lại LiDAR",{exact:true}).waitFor();
 assert(await page.getByText(`${frames[0].sampleToken}.f16`,{exact:true}).isVisible());
 assert(await page.getByLabel("Chú giải box").isVisible());
 measured.missingLidar=true;
 await page.unroute("**/api/media/**/lidar/**",missing);
 const down=async route=>route.fulfill({status:502,contentType:"application/json",body:JSON.stringify({error:{code:"worker_down",message:"Worker unavailable probe"}})});
 await page.route("**/api/jobs/**",down);
 for(const route of ["/review/m2_mini?sel=6987e5e71164","/review/context?job=m2_mini&sel=6987e5e71164",`/frame/${frames[0].sampleToken}?jobId=m2_mini&sel=6987e5e71164`]){
  await page.goto(origin+route);
  await page.getByText("Worker chưa chạy",{exact:true}).first().waitFor();
  assert(await page.getByRole("button",{name:"Sao chép lệnh",exact:true}).first().isVisible());
  assert(await page.getByRole("button",{name:"Thử lại",exact:true}).first().isVisible());
 }
 measured.offlineRoutes=3;
 await page.unroute("**/api/jobs/**",down);
 const slow=async route=>{await new Promise(resolve=>setTimeout(resolve,800));await route.continue();};
 await page.route("**/api/jobs/m2_mini/selections/6987e5e71164/frames?**",slow);
 await page.goto(frameUrl(frames[0].sampleToken));
 await page.getByText("Đang tải lô frame…",{exact:true}).waitFor();
 assert(await page.locator(".animate-pulse").count()>0);
 measured.loadingSkeleton=true;
 await page.getByLabel("Chú giải box").waitFor();
 await page.unroute("**/api/jobs/m2_mini/selections/6987e5e71164/frames?**",slow);
 await page.setViewportSize({width:390,height:844});
 await page.goto(`${origin}/?present=1`);
 await page.waitForFunction(()=>document.documentElement.dataset.present==="1");
 measured.mobile=await page.evaluate(()=>({width:innerWidth,scroll:document.documentElement.scrollWidth}));
 assert.equal(measured.mobile.width,measured.mobile.scroll);
 await page.screenshot({path:path.join(evidence,"home-present-mobile.png"),fullPage:true});
 assert.deepEqual(errors,[]);measured.pageErrors=errors;measured.exit=0;
 await writeFile(path.join(evidence,"browser.txt"),JSON.stringify(measured,null,2));
 console.log(JSON.stringify(measured,null,2));
} finally { await browser.close(); }
